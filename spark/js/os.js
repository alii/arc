const constants = constantsFor[given.platform];

// node lets these be used where a string is wanted: `${os.platform}`
function fact(value) {
  const read = () => value;
  read[Symbol.toPrimitive] = read;
  return read;
}

// with the encoding "buffer" the texts come as Buffers, which needs the
// buffer module to have been passed
function userInfo(options) {
  if (typeof options !== "object") options = null;
  const user = {
    uid: given.uid,
    gid: given.gid,
    username: given.username,
    homedir: given.homedir,
    shell: given.shell,
  };
  if (options?.encoding === "buffer") {
    const { Buffer } = require("node:buffer");
    for (const key of ["username", "homedir", "shell"]) {
      if (user[key] !== null) user[key] = Buffer.from(user[key]);
    }
  }
  return user;
}

